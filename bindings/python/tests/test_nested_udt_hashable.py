"""Nested-UDT-in-a-hashable-position read fidelity — issue #3500.

WHAT IS UNDER TEST
------------------
The Python binding projects a CQL ``set`` to a Python ``set`` and a CQL ``map``
to a Python ``dict``, so every set ELEMENT and every map KEY must be reduced to
a HASHABLE Python object. That reduction lives in
``bindings/python/src/value.rs`` (``value_to_hashable_key`` / ``contains_udt``)
and was **not total** over the ``cqlite_core::Value`` tree: a UDT reached
through a TUPLE or through a NESTED COLLECTION fell through to the generic
converter, which yields an unhashable ``dict``/``list``, and the whole
``SELECT`` raised.

Measured on this fixture BEFORE the fix (verbatim):

===============  ===========================================
column           exception
===============  ===========================================
s_tuple_udt      ``TypeError: unhashable type: 'dict'``
s_set_udt        ``TypeError: unhashable type: 'list'``
f_set_tuple_udt  ``TypeError: unhashable type: 'dict'``
``SELECT *``     ``TypeError: unhashable type: 'dict'``
===============  ===========================================

THE ORACLE
----------
Real Cassandra 5.0.2-written bytes:
``test-data/datasets/sstables/test_nested_udt_keys/nested_udt_keys-*`` (BIG
``nb``, uncompressed, 4 partitions), declared by
``test-data/schemas/nested-udt-keys.cql`` and generated by
``test-data/scripts/generate-nested-udt-keys.sh``. Every expectation below is
derived from the committed sstabledump golden ``nb-1-big-Data.db.jsonl`` plus
the generator's own INSERT statements — never from CQLite's prior output. A
CQLite-written/CQLite-read round trip could not detect this class at all.

Element ORDER is Cassandra's: a CQL ``set``/``map`` is stored sorted by the
serialized element/key, so the sequences asserted here are the golden's
cell-path order, not the insertion order.

WHY THESE TESTS ARE pytest AND NOT RUST ``#[test]``
---------------------------------------------------
``cargo test -p cqlite-py`` is structurally impossible — a pyo3 cdylib's test
harness cannot link libpython — so a Rust unit test beside the fix would
execute in no lane on any machine (``scripts/agent-gate.sh``'s
``binding-rust-tests`` census grep-counts those attributes precisely in order to
DECLARE them unrunnable). These run in the full gate's ``python-bindings``
component and the #1893 ``--lite`` python tier.

FAIL-CLOSED, NEVER SKIP (issue #3220)
-------------------------------------
``conftest.py`` resolves ONE corpus root and prefers ``$CQLITE_DATASETS_ROOT``,
so an in-repo COMMITTED fixture is invisible to it and ``skip_if_no_datasets()``
would skip green forever. Neither root is a superset of the other, so no fixed
env-first/checkout-first rule is correct. This module therefore resolves the
corpus root PER TABLE by walking EVERY candidate root for that table's
``*-Data.db`` (the Python mirror of
``cqlite-core/tests/support/datasets_root.rs::sstables_root_for_table``) and
asserts PER CASE: the fixture is git-committed, so it is ``must_run`` and
fail-closed UNCONDITIONALLY — there is no ``pytest.skip`` in this file and no
suite-wide ``assert ran > 0`` (which cannot see one case skipping behind its
siblings).
"""

import os
from pathlib import Path

import pytest

import cqlite

KEYSPACE = "test_nested_udt_keys"
TABLE = "nested_udt_keys"
SCHEMA_FILE = "nested-udt-keys.cql"


# =============================================================================
# Root resolution — committed schema checkout-relative (#3148), corpus per
# table across EVERY candidate root (#3220). Deliberately local to this module:
# conftest's single-root constants are the thing that would hide the fixture.
# =============================================================================


def _workspace_root() -> Path:
    """The checkout root, anchored on the workspace-root ``Cargo.toml`` marker.

    Same rule as ``test-data/support/fixture_roots.rs::workspace_root`` — the
    nearest ancestor whose ``Cargo.toml`` declares ``[workspace]``. Anchoring on
    a marker rather than counting ``..`` levels keeps this correct if the file
    ever moves.
    """
    here = Path(__file__).resolve()
    for ancestor in here.parents:
        manifest = ancestor / "Cargo.toml"
        if not manifest.is_file():
            continue
        try:
            text = manifest.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if any(line.lstrip().startswith("[workspace]") for line in text.splitlines()):
            return ancestor
    raise AssertionError(
        f"no [workspace] Cargo.toml found in any ancestor of {here} — cannot "
        "resolve the checkout root for the committed #3500 fixture"
    )


def _schemas_root() -> Path:
    """The COMMITTED schema-fixture root.

    Checkout-relative source, never derived from ``CQLITE_DATASETS_ROOT``.
    ``CQLITE_SCHEMAS_ROOT`` is an optional out-of-tree override and MUST be
    absolute: the gate resolves a relative value against the repo root while
    pytest runs from the package dir, so it would certify one schemas root while
    the tests read another (#3148). A relative value is REJECTED, never resolved.
    """
    raw = os.environ.get("CQLITE_SCHEMAS_ROOT")
    if raw is not None and raw.strip():
        if any(ord(ch) < 32 or ord(ch) == 127 for ch in raw):
            pytest.fail(
                f"CQLITE_SCHEMAS_ROOT must not contain control characters, got {raw!r}"
            )
        override = Path(raw)
        if not override.is_absolute():
            pytest.fail(
                f"CQLITE_SCHEMAS_ROOT must be an ABSOLUTE path, got {raw!r} — a "
                "relative value cannot mean the same thing to the gate (CWD = repo "
                "root) and to pytest (CWD = package dir), so the gate would certify "
                "a schemas root the run never used (#3148)"
            )
        if override.is_dir():
            return override
    return _workspace_root() / "test-data" / "schemas"


def _sstables_root_candidates() -> list[Path]:
    """Every ``sstables/`` root to search, in order.

    An ORDER, not a preference: ``_sstables_root_for_table`` picks by EVIDENCE
    (which root actually holds the table), because neither root is a superset of
    the other — the fetched corpus carries keyspaces the checkout does not, and
    the checkout carries committed fixtures (this one) the fetched corpus does
    not (#3104/#3220).
    """
    candidates: list[Path] = []
    env_root = os.environ.get("CQLITE_DATASETS_ROOT")
    if env_root and env_root.strip():
        root = Path(env_root)
        nested = root / "sstables"
        candidates.append(nested if nested.is_dir() else root)
    checkout = _workspace_root() / "test-data" / "datasets" / "sstables"
    if checkout not in candidates:
        candidates.append(checkout)
    return candidates


def _table_has_data(root: Path, keyspace: str, table: str) -> bool:
    """True when ``<root>/<keyspace>/<table>-*/`` holds a ``*-Data.db`` FILE.

    Presence is judged by a real Data.db component, never by directory
    existence: this repo commits JSONL sidecars for fixtures whose binaries are
    gitignored, so a ``<table>-<uuid>/`` dir can exist with no SSTable in it.
    """
    ks_dir = root / keyspace
    if not ks_dir.is_dir():
        return False
    prefix = f"{table}-"
    try:
        table_dirs = [
            d for d in ks_dir.iterdir() if d.is_dir() and d.name.startswith(prefix)
        ]
    except OSError:
        return False
    for table_dir in table_dirs:
        try:
            entries = list(table_dir.iterdir())
        except OSError:
            continue
        if any(e.is_file() and e.name.endswith("-Data.db") for e in entries):
            return True
    return False


def _sstables_root_for_table(keyspace: str, table: str) -> Path:
    """The candidate root that really carries ``<keyspace>/<table>-*/…-Data.db``.

    FAIL-CLOSED, naming every root searched. This fixture is git-committed, so
    "not found" is a broken checkout or a broken resolver — never a reason to
    skip.
    """
    candidates = _sstables_root_candidates()
    for root in candidates:
        if _table_has_data(root, keyspace, table):
            return root
    searched = ", ".join(str(c) for c in candidates)
    raise AssertionError(
        f"COMMITTED fixture {keyspace}.{table} carries no *-Data.db under any "
        f"candidate root — searched [{searched}]. This fixture is checked into git "
        "(issue #3500), so this is a broken checkout or a broken resolver, not a "
        "missing download; it must never be skipped (#3220)."
    )


@pytest.fixture(scope="module")
def db():
    """Open the #3500 fixture through the real binding. Never skips."""
    root = _sstables_root_for_table(KEYSPACE, TABLE)
    schema = _schemas_root() / SCHEMA_FILE
    assert schema.is_file(), (
        f"committed schema {schema} is unreadable — it is checked-in source "
        "(#3148), so this is fail-closed, not a skip"
    )
    with cqlite.open(root, schema=schema) as database:
        yield database


def _rows_by_id(database, projection: str) -> dict:
    """``{id: row}`` for a projection, asserting all four partitions arrived."""
    result = database.execute(f"SELECT id, {projection} FROM {KEYSPACE}.{TABLE}")
    rows = {row.get("id"): row for row in result.rows}
    assert sorted(rows) == [1, 2, 3, 4], (
        f"expected partitions 1..4 from the committed fixture, got {sorted(rows)}"
    )
    return rows


