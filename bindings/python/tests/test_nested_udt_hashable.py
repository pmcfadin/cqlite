"""Nested-UDT-in-a-hashable-position read fidelity — issue #3500.

WHAT IS UNDER TEST
------------------
The Python binding projects a CQL ``set`` to a Python ``set`` and a CQL ``map``
to a Python ``dict``, so every set ELEMENT and every map KEY must be reduced to
a HASHABLE Python object. That reduction lives in
``bindings/python/src/value_hashable.rs`` (``value_to_hashable_key`` /
``contains_udt``, split out of ``value.rs`` by #3500)
and was **not total** over the ``cqlite_core::Value`` tree: a UDT reached
through a TUPLE or through a NESTED COLLECTION fell through to the generic
converter, which yields an unhashable ``dict``/``list``, and the whole
``SELECT`` raised.

Measured on this fixture BEFORE the fix (verbatim):

===============  ===========================================
column           exception
===============  ===========================================
s_tuple_udt      ``TypeError: unhashable type: 'dict'``
s_set_udt        ``TypeError: unhashable type: 'list'``
f_set_tuple_udt  ``TypeError: unhashable type: 'dict'``
f_map_tuple_udt  ``TypeError: unhashable type: 'dict'``
f_map_set_udt    ``TypeError: unhashable type: 'list'``
``SELECT *``     ``TypeError: unhashable type: 'dict'``
===============  ===========================================

WHICH COLUMNS COVER ``value_to_hashable_key``, AND WHICH DO NOT
---------------------------------------------------------------
Stated in exactly ONE place, and deliberately not restated here: the ROUTING
section of ``bindings/python/src/value_hashable.rs``, which gives the route and
the ARM for all ten columns. Read it before adding, deleting or re-scoping any
coverage claim in this module.

This module asserts nothing about that routing, because restating it is what
went wrong: the claim was made in several places here and in both fixture
headers and drifted in all but one, always as the same over-broad "only the
frozen maps reach the function at all". Reach and per-arm split stay at ROUTING:
a routing-derived COUNT or exclusivity claim decays when a column is added.
Hence the rule that survives here: scope a claim to the ARM, not the function.

``contains_udt`` IS A SEPARATE MATTER, AND ITS ``Map`` ARM NEEDED ITS OWN
COLUMNS. ``set_to_py`` is that function's only caller, so the value it inspects
is always a SET ELEMENT — a ``Map`` at the TOP of a column is never passed to
it. Its ``Map`` arm (``any(|(k, v)| contains_udt(k) || contains_udt(v))``) was
therefore covered by NOTHING until ``s_map_udt_key`` / ``s_map_udt_val`` put a
frozen map INSIDE a set element, one column per half because ``||``
short-circuits. A regression there is SILENT rather than a ``TypeError``: the
hashable projection is total, so the element still projects hashably and the
column merely comes back as a ``frozenset`` instead of #804's ``list`` of
``dict``s. See :class:`TestSetElementFrozenMapWithUdtKeyHalf`.

THE ORACLE
----------
Real Cassandra 5.0.2-written bytes:
``test-data/datasets/sstables/test_nested_udt_keys/nested_udt_keys-*`` (BIG
``nb``, uncompressed, 4 partitions), declared by
``test-data/schemas/nested-udt-keys.cql`` and generated by
``test-data/scripts/generate-nested-udt-keys.sh``. Every expectation below is
derived from the committed sstabledump golden ``nb-1-big-Data.db.jsonl`` plus
the generator's own INSERT statements — never from CQLite's prior output. A
CQLite-written/CQLite-read round trip could not detect this class at all.

Element ORDER is Cassandra's: a CQL ``set``/``map`` is stored sorted by the
serialized element/key, so the sequences asserted here are the golden's
cell-path order, not the insertion order.

WHY THESE TESTS ARE pytest AND NOT RUST ``#[test]``
---------------------------------------------------
``cargo test -p cqlite-py`` is structurally impossible — a pyo3 cdylib's test
harness cannot link libpython — so a Rust unit test beside the fix would
execute in no lane on any machine (``scripts/agent-gate.sh``'s
``binding-rust-tests`` census grep-counts those attributes precisely in order to
DECLARE them unrunnable). These run in the full gate's ``python-bindings``
component and the #1893 ``--lite`` python tier.

FAIL-CLOSED, NEVER SKIP (issue #3220)
-------------------------------------
``conftest.py`` resolves ONE corpus root and prefers ``$CQLITE_DATASETS_ROOT``,
so an in-repo COMMITTED fixture is invisible to it and ``skip_if_no_datasets()``
would skip green forever. Neither root is a superset of the other, so no fixed
env-first/checkout-first rule is correct. This module therefore resolves the
corpus root PER TABLE by searching EVERY candidate root — and it searches for
the GENERATION the committed ``references.yml`` declares (directory basename +
SSTable prefix), not merely for the table NAME, because a table name does not
identify bytes: this fixture has six retired generations, and any leftover copy
of one shadowed the committed fixture and became the oracle. An undeclared
generation, an ambiguous pair of roots and a declared generation present nowhere
each FAIL, named. Assertions are PER CASE: the fixture is git-committed, so it
is ``must_run`` and fail-closed UNCONDITIONALLY — there is no ``pytest.skip`` in
this file and no suite-wide ``assert ran > 0`` (which cannot see one case
skipping behind its siblings).
"""

