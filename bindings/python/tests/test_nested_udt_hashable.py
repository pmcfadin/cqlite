class TestTupleBorneUdtInSetElement:
    """``s_tuple_udt`` — ``set<frozen<tuple<frozen<key_part>, int>>>``.

    Issue #3500 shape 1: the UDT is reached through a TUPLE. Before the fix this
    raised ``TypeError: unhashable type: 'dict'`` — ``contains_udt`` did not
    traverse ``Tuple``, so the set took the frozenset path, and
    ``value_to_hashable_key`` had no ``Tuple`` arm so the element became a
    Python tuple containing an unhashable ``dict``.
    """

    def test_multi_element_partition(self, db):
        """id=1: three tuples, two sharing the same UDT with different ints.

        Order is Cassandra's sorted order (golden cell paths ``alpha\\:1:1``,
        ``alpha\\:1:2``, ``zulu\\:26:7``), NOT the insertion order.
        """
        row = _rows_by_id(db, "s_tuple_udt")[1]
        assert row.get("s_tuple_udt") == [
            (kp("alpha", 1), 1),
            (kp("alpha", 1), 2),
            (kp("zulu", 26), 7),
        ]

    def test_null_udt_fields(self, db):
        """id=2: NULL UDT fields inside the hashable position.

        Reaches ``value_to_hashable_key``'s ``None => py.None()`` UDT-field
        branch, which no committed fixture previously exercised inside a
        hashable position. Golden order: ``\\@\\:5:2`` then
        ``nullrank\\:\\@:1`` (``\\@`` is sstabledump's null marker).
        """
        row = _rows_by_id(db, "s_tuple_udt")[2]
        assert row.get("s_tuple_udt") == [
            (kp(None, 5), 2),
            (kp("nullrank", None), 1),
        ]

    def test_single_element_partition(self, db):
        """id=3: exactly one element, the same UDT value as the other columns."""
        row = _rows_by_id(db, "s_tuple_udt")[3]
        assert row.get("s_tuple_udt") == [(kp("solo", 99), 42)]

    def test_sparse_row(self, db):
        """id=4: the ONLY column written in that partition.

        The sparse row exercises the missing-column path alongside a populated
        hashable-position column: every other column of id=4 must be ``None``
        while this one decodes.
        """
        rows = _rows_by_id(db, "s_tuple_udt")
        assert rows[4].get("s_tuple_udt") == [(kp("partial", 4), 4)]

    def test_elements_are_plain_tuples_and_dicts(self, db):
        """Exact Python types, not merely equal structures."""
        value = _rows_by_id(db, "s_tuple_udt")[3].get("s_tuple_udt")
        assert type(value) is list
        assert type(value[0]) is tuple
        assert type(value[0][0]) is dict
        assert type(value[0][1]) is int


