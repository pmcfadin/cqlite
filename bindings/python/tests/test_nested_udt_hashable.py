def _workspace_root() -> Path:
    """The checkout root, anchored on the workspace-root ``Cargo.toml`` marker.

    Same rule as ``test-data/support/fixture_roots.rs::workspace_root`` — the
    nearest ancestor whose ``Cargo.toml`` declares ``[workspace]``. Anchoring on
    a marker rather than counting ``..`` levels keeps this correct if the file
    ever moves.
    """
    here = Path(__file__).resolve()
    for ancestor in here.parents:
        manifest = ancestor / "Cargo.toml"
        if not manifest.is_file():
            continue
        try:
            text = manifest.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if any(line.lstrip().startswith("[workspace]") for line in text.splitlines()):
            return ancestor
    raise AssertionError(
        f"no [workspace] Cargo.toml found in any ancestor of {here} — cannot "
        "resolve the checkout root for the committed #3500 fixture"
    )


def _schemas_root() -> Path:
    """The COMMITTED schema-fixture root.

    Checkout-relative source, never derived from ``CQLITE_DATASETS_ROOT``.
    ``CQLITE_SCHEMAS_ROOT`` is an optional out-of-tree override and MUST be
    absolute: the gate resolves a relative value against the repo root while
    pytest runs from the package dir, so it would certify one schemas root while
    the tests read another (#3148). A relative value is REJECTED, never resolved.

    An override that is absolute but NOT a readable directory is rejected too.
    It used to fall back silently to the checkout, which is the guessing posture
    #3148 exists to remove: the operator asked for one schemas root, the run
    used another, and the report said nothing. Both refusals name the value.
    """
    raw = os.environ.get("CQLITE_SCHEMAS_ROOT")
    if raw is not None and raw.strip():
        if any(ord(ch) < 32 or ord(ch) == 127 for ch in raw):
            pytest.fail(
                f"CQLITE_SCHEMAS_ROOT must not contain control characters, got {raw!r}"
            )
        override = Path(raw)
        if not override.is_absolute():
            pytest.fail(
                f"CQLITE_SCHEMAS_ROOT must be an ABSOLUTE path, got {raw!r} — a "
                "relative value cannot mean the same thing to the gate (CWD = repo "
                "root) and to pytest (CWD = package dir), so the gate would certify "
                "a schemas root the run never used (#3148)"
            )
        if not override.is_dir():
            pytest.fail(
                f"CQLITE_SCHEMAS_ROOT={raw!r} is absolute but is not a readable "
                "directory — refused rather than silently falling back to the "
                "checkout, which would run against a schemas root the operator "
                "did not ask for (#3148)"
            )
        return override
    return _workspace_root() / "test-data" / "schemas"


def _same_physical_dir(a: Path, b: Path) -> bool:
    """True when two candidate spellings name ONE directory on disk.

    Compares THINGS, not representations. Candidate roots used to be
    deduplicated LEXICALLY, so an env var reaching the checkout corpus through a
    symlink or a relative path added the SAME directory twice and the ambiguity
    refusal below then rejected it as "two roots carry the declared generation"
    — a false FAIL in a legitimate configuration (the fetch script prints an
    export line and operators point it at whatever path they have).

    ``samefile`` (st_dev, st_ino) is the primary test because it settles every
    alias shape a lexical compare cannot: symlink, relative spelling, trailing
    ``.``, bind mount, hardlinked directory. It requires BOTH paths to exist, so
    a nonexistent candidate falls back to ``os.path.realpath``, which never
    raises, resolves a broken symlink by its recorded target and normalises a
    missing tail lexically. A nonexistent candidate is deliberately KEPT in the
    list rather than dropped — the "searched [...]" diagnostic has to name the
    root the operator actually exported, or a typo'd ``CQLITE_DATASETS_ROOT``
    disappears from the one report that would reveal it — and being kept is
    safe precisely because it is normalised: it can never crash the resolver and
    never counts as a second root when it is another spelling of the same
    missing path.

    NOT a resolution for DISPLAY: only the dedup KEY is normalised. Diagnostics
    keep the operator's own spelling, which is what they have to recognise.
    """
    try:
        return a.samefile(b)
    except OSError:
        return os.path.realpath(a) == os.path.realpath(b)


def _sstables_root_candidates() -> list[Path]:
    """Every ``sstables/`` root to search, in order.

    An ORDER, not a preference: ``_sstables_root_for_table`` picks by EVIDENCE
    (which root holds the generation ``references.yml`` DECLARES), because
    neither root is a superset of the other — the fetched corpus carries
    keyspaces the checkout does not, and the checkout carries committed fixtures
    (this one) the fetched corpus does not (#3104/#3220). Every candidate is
    inspected on every call; nothing short-circuits on the first hit, because an
    undeclared or duplicated generation in a LATER root is itself a failure.

    Deduplicated PHYSICALLY (``_same_physical_dir``), never lexically: an alias
    of a root already listed is not a second root.
    """
    candidates: list[Path] = []
    env_root = os.environ.get("CQLITE_DATASETS_ROOT")
    if env_root and env_root.strip():
        root = Path(env_root)
        nested = root / "sstables"
        candidates.append(nested if nested.is_dir() else root)
    checkout = _workspace_root() / "test-data" / "datasets" / "sstables"
    if not any(_same_physical_dir(checkout, c) for c in candidates):
        candidates.append(checkout)
    return candidates


def _table_generations(root: Path, keyspace: str, table: str) -> list[str]:
    """Sorted basenames of ``<root>/<keyspace>/<table>-*/`` dirs holding a Data.db.

    Presence is judged by a real ``*-Data.db`` component, never by directory
    existence: this repo commits JSONL sidecars for fixtures whose binaries are
    gitignored, so a ``<table>-<uuid>/`` dir can exist with no SSTable in it.
    Sorted so every diagnostic built from it is deterministic.
    """
    ks_dir = root / keyspace
    if not ks_dir.is_dir():
        return []
    prefix = f"{table}-"
    try:
        table_dirs = [
            d for d in ks_dir.iterdir() if d.is_dir() and d.name.startswith(prefix)
        ]
    except OSError:
        return []
    found: list[str] = []
    for table_dir in table_dirs:
        try:
            entries = list(table_dir.iterdir())
        except OSError:
            continue
        if any(e.is_file() and e.name.endswith("-Data.db") for e in entries):
            found.append(table_dir.name)
    return sorted(found)


def _table_has_data(root: Path, keyspace: str, table: str) -> bool:
    """True when ``root`` carries ANY generation of ``<keyspace>.<table>``."""
    return bool(_table_generations(root, keyspace, table))


#: Manifest keys this module reads out of a ``references.yml`` table entry.
_MANIFEST_ENTRY_KEYS = ("keyspace", "table", "sstable_dir", "prefix")


def _manifest_declared_generation(keyspace: str, table: str) -> tuple[str, str]:
    """``(table-dir basename, sstable prefix)`` that ``references.yml`` DECLARES.

    THE DISCRIMINATOR, and the reason it is needed: a table NAME does not
    identify a generation. This fixture has been regenerated six times, each
    time minting a NEW Cassandra table UUID and hence a new directory basename,
    so any leftover generation in any searched root matched by name and became
    the oracle — a stale, corrupt or merely DIFFERENT set of bytes nobody
    reviewed. Resolving against the manifest asks "is this the generation the
    committed manifest names?" instead of "which root do I prefer?", which is
    why it is taken over a checkout-first preference ordering: neither root is a
    superset of the other (#3220), and this test is strictly stronger — it
    rejects a stale generation in EITHER root, the checkout included.

    ``references.yml`` is committed source, so it is read checkout-relative,
    exactly like the CQL schemas (#3148), never from ``CQLITE_DATASETS_ROOT`` —
    a manifest inside the corpus being validated could not discriminate anything.
    The basename (not the recorded path) is the subject, mirroring
    ``dataset_helpers::resolve_table_dir_via_manifest``, which also takes
    ``file_name()`` and re-roots it: older entries in that file carry the
    generating machine's absolute paths.

    NOT A YAML PARSER. It reads the flat, machine-emitted block shape
    ``test-data/scripts/generate-nested-udt-keys.sh`` writes (a ``tables:``
    sequence of two-space list items whose scalars sit at four spaces) and
    FAILS CLOSED on anything else — a missing ``tables:``, no parsed entries, a
    duplicated key, zero or several entries for this table, an unusable
    basename or prefix. PyYAML is deliberately not used: the gate's throwaway
    venv installs only ``maturin`` and ``pytest``, so an ``import yaml`` here
    would be an ImportError in the one lane that matters.
    """
    manifest = _workspace_root() / "test-data" / "datasets" / "references.yml"
    try:
        lines = manifest.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise AssertionError(
            f"the committed dataset manifest {manifest} is unreadable ({exc}) — "
            "it declares which fixture GENERATION is the oracle, so the run is "
            "refused rather than resolved by table name alone (#3500)"
        ) from exc

    entries: list[dict[str, str]] = []
    in_tables = False
    for raw in lines:
        line = raw.rstrip()
        if not in_tables:
            if line == "tables:":
                in_tables = True
            continue
        if line.startswith("  - "):
            entries.append({})
            line = "    " + line[4:]
        if not entries:
            continue
        field = re.fullmatch(r" {4}([a-z_]+): *(.*)", line)
        if field is None:
            continue
        key, value = field.group(1), field.group(2).strip().strip('"')
        if key not in _MANIFEST_ENTRY_KEYS:
            continue
        if key in entries[-1]:
            raise AssertionError(
                f"{manifest} declares {key!r} twice in one table entry "
                f"({entries[-1][key]!r} then {value!r}) — refused rather than "
                "letting last-one-wins choose the fixture generation (#3500)"
            )
        entries[-1][key] = value

    if not in_tables or not entries:
        raise AssertionError(
            f"{manifest} yielded no table entries (tables: header "
            f"{'found' if in_tables else 'ABSENT'}) — the manifest shape this "
            "reader expects has changed, so it can no longer say which fixture "
            "generation is the oracle; fix the reader, do not fall back to "
            "resolving by table name (#3500)"
        )

    matching = [
        e for e in entries if e.get("keyspace") == keyspace and e.get("table") == table
    ]
    if len(matching) != 1:
        raise AssertionError(
            f"{manifest} declares {len(matching)} entries for {keyspace}.{table}, "
            f"expected exactly 1 (parsed {len(entries)} entries in total) — with "
            "no single declared generation this run cannot tell the committed "
            "fixture from a leftover one, so it is refused (#3500)"
        )
    entry = matching[0]
    dirname = PurePosixPath(entry.get("sstable_dir", "")).name
    prefix = entry.get("prefix", "")
    if not dirname.startswith(f"{table}-") or not prefix or "/" in prefix:
        raise AssertionError(
            f"{manifest} entry for {keyspace}.{table} is unusable: sstable_dir "
            f"basename {dirname!r} (expected '{table}-<uuid>'), prefix "
            f"{prefix!r} (expected e.g. 'nb-1-big')"
        )
    return dirname, prefix


def _resolve_declared_generation(
    keyspace: str, table: str, dirname: str, prefix: str
) -> Path:
    """The ONE candidate root carrying the manifest-declared generation.

    Fail-closed, loudly, in all three bad states — never a silent skip and
    never a silent fallback to another root:

    * a root holding a generation of this table that the manifest does NOT
      declare (or the declared directory without the declared ``prefix``) is
      REJECTED naming the root, what was found and what is declared, even when
      another root does carry the declared generation: an operator whose
      exported corpus holds unreviewed bytes for this table has to hear it,
      because that corpus WAS the oracle before this check existed;
    * two roots both carrying the declared generation are compared BY CONTENT —
      the WHOLE component set (every file in the generation directory, plus the
      TOC.txt manifest and the file NAMES), not just ``Data.db``: the reader
      consumes Index/Statistics/Summary/TOC too, so matching data files alone do
      not make two roots the same fixture (roborev job 305).
      Byte-identical copies are not ambiguity — they are the same fixture reached
      by two paths, which becomes the NORMAL state as soon as the fetched corpus
      ships a git-committed fixture (roborev job 302, Medium: refusing it would
      red every environment that has both an exported root and the checkout).
      Copies resolve to the first; generations that DIFFER are still refused,
      because that is the shadowing case this check exists for. Decided by
      evidence, never by a preference ordering (#3220);
    * no root carrying it names every root searched. The fixture is
      git-committed, so this is a broken checkout or a broken resolver, never a
      reason to skip (#3220).
    """
    candidates = _sstables_root_candidates()
    searched = ", ".join(str(c) for c in candidates)
    matches: list[Path] = []
    rejected: list[str] = []
    for root in candidates:
        generations = _table_generations(root, keyspace, table)
        if (root / keyspace / dirname / f"{prefix}-Data.db").is_file():
            matches.append(root)
        elif dirname in generations:
            rejected.append(
                f"{root} holds the declared directory {dirname!r} but it carries "
                f"no {prefix}-Data.db"
            )
        for other in sorted(set(generations) - {dirname}):
            rejected.append(
                f"{root} holds {other!r}, which is NOT the declared generation"
            )
    if rejected:
        raise AssertionError(
            f"corpus root(s) carry a {keyspace}.{table} generation the committed "
            f"references.yml does not declare — declared {dirname!r} (prefix "
            f"{prefix!r}); found: " + "; ".join(rejected) + ". A same-named table "
            "directory used to SHADOW the committed fixture and silently become "
            "the oracle, so this is refused rather than resolved: delete or move "
            "the undeclared generation (#3500)"
        )
    if len(matches) > 1:
        # COMPARE THE BYTES rather than refusing on count. Two roots carrying the
        # declared generation are ambiguous only if they carry DIFFERENT bytes;
        # identical copies are one fixture reached two ways, which is what an
        # exported corpus plus a git-committed fixture looks like. Refusing that
        # would red every normal environment once the corpus ships this table
        # (roborev job 302). A preference ordering still cannot tell two
        # generations apart — so this does not use one; it uses the evidence.
        # THE WHOLE COMPONENT SET, not just Data.db (roborev job 305, Medium).
        # A root carrying the same Data.db but a different or missing Index.db,
        # Statistics.db, Summary.db or TOC.txt is NOT the same fixture — the reader
        # consumes all of them, so two such roots can produce different reads while
        # their data files match byte for byte. Hashing one component would have
        # called them identical and picked one.
        #
        # The component set is derived from TOC.txt where present (Cassandra's own
        # manifest of what it wrote) and cross-checked against the directory, so a
        # component TOC lists but the directory lacks is a difference too — and the
        # digest covers the file NAMES as well as their bytes, so an extra or
        # missing component separates the roots rather than being ignored.
        digests: dict[str, list[Path]] = {}
        for root in matches:
            gen_dir = root / keyspace / dirname
            present = sorted(q.name for q in gen_dir.iterdir() if q.is_file())
            toc = gen_dir / f"{prefix}-TOC.txt"
            declared: list[str] = []
            if toc.is_file():
                declared = sorted(
                    line.strip()
                    for line in toc.read_text().splitlines()
                    if line.strip()
                )
            parts: list[str] = [f"TOC:{','.join(declared)}", f"DIR:{','.join(present)}"]
            for name in present:
                body = hashlib.sha256((gen_dir / name).read_bytes()).hexdigest()
                parts.append(f"{name}:{body}")
            digest = hashlib.sha256("\n".join(parts).encode()).hexdigest()
            digests.setdefault(digest, []).append(root)
        if len(digests) > 1:
            detail = "; ".join(
                f"{d[:12]}: " + ", ".join(str(r) for r in roots)
                for d, roots in sorted(digests.items())
            )
            raise AssertionError(
                f"AMBIGUOUS: {len(matches)} candidate roots carry the declared "
                f"{keyspace}.{table} generation {dirname!r} with "
                f"{len(digests)} DIFFERENT contents — {detail}. Refused rather "
                "than picking one: same-named generations with different bytes "
                "are the shadowing case this resolver exists to catch, and no "
                "preference ordering can tell them apart (#3500)"
            )
    if not matches:
        raise AssertionError(
            f"the COMMITTED {keyspace}.{table} generation declared by "
            f"references.yml ({dirname}/{prefix}-Data.db) is present under no "
            f"candidate root — searched [{searched}]. This fixture is checked "
            "into git (issue #3500), so this is a broken checkout or a broken "
            "resolver, not a missing download; it must never be skipped (#3220)."
        )
    return matches[0]


