class TestSelectStarWholeRow:
    """``SELECT *`` over every partition — the shape a user actually runs.

    Before the fix this raised ``TypeError: unhashable type: 'dict'`` on the
    first partition, so NO row of this table was readable at all.
    """

    def test_select_star_returns_every_partition(self, db):
        """All four partitions decode, in Murmur3 token order 1, 2, 4, 3."""
        result = db.execute(f"SELECT * FROM {KEYSPACE}.{TABLE}")
