# ------------------------------------------------------------ input validation
ws0_require_inputs() {
  [ -n "$WS0_STAGE" ]       || ws0_die "WS0_STAGE unset (staged SSTable dir; corpus is generated by a peer agent, never hardcoded)"
  [ -d "$WS0_STAGE" ]       || ws0_die "WS0_STAGE=$WS0_STAGE is not a directory"
  [ -n "$WS0_FLIGHT_BIN" ]  || ws0_die "WS0_FLIGHT_BIN unset (path to cqlite-flight)"
  [ -x "$WS0_FLIGHT_BIN" ]  || ws0_die "WS0_FLIGHT_BIN=$WS0_FLIGHT_BIN is not executable"
  [ -n "$WS0_LOADGEN_BIN" ] || ws0_die "WS0_LOADGEN_BIN unset (path to flight-loadgen)"
  [ -x "$WS0_LOADGEN_BIN" ] || ws0_die "WS0_LOADGEN_BIN=$WS0_LOADGEN_BIN is not executable"
  [ -n "$WS0_TICKET_TPL" ]  || ws0_die "WS0_TICKET_TPL unset (--ticket-template JSON)"
  [ -f "$WS0_TICKET_TPL" ]  || ws0_die "WS0_TICKET_TPL=$WS0_TICKET_TPL not found"
  # #3217's check tested only 1-2 levels, so the CORRECT layout warned. The
  # layout cqlite-flight actually discovers is <keyspace>/<table>-<uuid>/, i.e.
  # THREE levels down — and a flat stage (which this check ACCEPTED) makes the
  # server log "discovered 0 tables across 0 keyspaces" and every request
  # NotFound. So search at any depth, and require at least one Data.db.
  local ndata
  ndata="$(find "$WS0_STAGE" -name '*-Data.db' -type f 2>/dev/null | wc -l)"
  [ "$ndata" -gt 0 ] || ws0_die "no *-Data.db anywhere under WS0_STAGE=$WS0_STAGE"
  ls "$WS0_STAGE"/*/*/*-Data.db >/dev/null 2>&1 || \
    ws0_warn "WS0_STAGE=$WS0_STAGE has $ndata Data.db but not at the <keyspace>/<table-uuid>/ depth cqlite-flight discovers — a flat stage yields 'discovered 0 tables' and all-NotFound"
}

# ------------------------------------------------------------ server lifecycle
# ws0_start_server <server-cpu-list> <merge-path: bypass|merge> <log-file>
# Exports WS0_SERVER_PID. Blocks until the port answers (<=60s) or dies.
ws0_start_server() {
  local cpus="$1" merge_path="$2" logfile="$3"
  mkdir -p "$(dirname "$logfile")"
  ws0_log "starting cqlite-flight on cpus=$cpus merge_path=$merge_path numa-node=$WS0_NUMA_NODE"
  # NUMA binding (RUNBOOK step 3 rule 2) — NEW vs #3217, whose host had one node.
  # --cpunodebind confines scheduling to node N and --membind confines page-cache
  # and heap allocation to node N's memory, so a far-node allocation cannot be an
  # alternative explanation for an IPC delta. taskset then pins to the exact set
  # inside that node. Recorded in the run config verbatim.
  CQLITE_FLIGHT_MERGE_PATH="$merge_path" \
  numactl --cpunodebind="$WS0_NUMA_NODE" --membind="$WS0_NUMA_NODE" \
  taskset -c "$cpus" "$WS0_FLIGHT_BIN" \
      --data-dir "$WS0_STAGE" \
      --listen "${WS0_LISTEN_HOST}:${WS0_LISTEN_PORT}" \
      --batch-size "$WS0_BATCH_SIZE" \
      --max-batch-bytes "$WS0_MAX_BATCH_BYTES" \
      --max-inflight-egress-bytes "$WS0_MAX_INFLIGHT_EGRESS_BYTES" \
      --max-concurrent-scans "$WS0_MAX_CONCURRENT_SCANS" \
      --admission-wait-timeout-ms "$WS0_ADMISSION_WAIT_TIMEOUT_MS" \
      >"$logfile" 2>&1 &
  WS0_SERVER_PID=$!
  export WS0_SERVER_PID
  local i
  for i in $(seq 1 60); do
    if ! kill -0 "$WS0_SERVER_PID" 2>/dev/null; then
      ws0_die "cqlite-flight (pid $WS0_SERVER_PID) died during startup; see $logfile"
    fi
    if (echo >"/dev/tcp/${WS0_LISTEN_HOST}/${WS0_LISTEN_PORT}") 2>/dev/null; then
      ws0_log "server ready pid=$WS0_SERVER_PID after ${i}s"
      return 0
    fi
    sleep 1
  done
  ws0_stop_server
  ws0_die "server did not accept on ${WS0_LISTEN_HOST}:${WS0_LISTEN_PORT} within 60s; see $logfile"
}

# TRAP 2: explicit PID only. `pkill -f 'cqlite-flight --data-dir'` matches the
# launching shell's own command line and kills the harness. Never use it.
ws0_stop_server() {
  local pid="${1:-${WS0_SERVER_PID:-}}"
  [ -n "$pid" ] || return 0
  kill -0 "$pid" 2>/dev/null || { unset WS0_SERVER_PID || true; return 0; }
  ws0_log "stopping server pid=$pid"
  kill -TERM "$pid" 2>/dev/null || true
  local i
  for i in $(seq 1 15); do kill -0 "$pid" 2>/dev/null || break; sleep 1; done
  kill -0 "$pid" 2>/dev/null && kill -9 "$pid" 2>/dev/null || true
  wait "$pid" 2>/dev/null || true
  unset WS0_SERVER_PID || true
}

# ------------------------------------------------------------- counter helpers
# CPU seconds consumed by a pid (utime+stime), from /proc/<pid>/stat fields 14,15.
ws0_proc_cpu_secs() {
  local pid="$1"
  awk -v hz="$(getconf CLK_TCK)" '{print ($14+$15)/hz}' "/proc/$pid/stat" 2>/dev/null || echo 0
}
# /proc/<pid>/io as compact JSON. rchar / read_bytes / syscr are reported
# SEPARATELY and are NEVER divided by one another (different units, different
# layers) — see README.
ws0_proc_io_json() {
  local pid="$1"
  python3 -c '
import json,sys
d={}
try:
    for line in open("/proc/%s/io"%sys.argv[1]):
        k,v=line.split(":"); d[k.strip()]=int(v)
except OSError: pass
print(json.dumps(d))' "$pid"
}
# voluntary / nonvoluntary context switches from /proc/<pid>/status (AC5).
ws0_proc_ctxt_json() {
  local pid="$1"
  python3 -c '
import json,sys
d={}
try:
    for line in open("/proc/%s/status"%sys.argv[1]):
        if line.startswith(("voluntary_ctxt_switches","nonvoluntary_ctxt_switches")):
            k,v=line.split(":"); d[k.strip()]=int(v)
except OSError: pass
print(json.dumps(d))' "$pid"
}
# Aggregate CPU busy seconds over a CPU list, from /proc/stat (used for the
# CLIENT-set utilisation validity gate, which must not depend on knowing the
# client's pid tree).
ws0_cpuset_busy_secs() {
  python3 -c '
import sys
want=set()
for part in sys.argv[1].split(","):
    if "-" in part:
        a,b=part.split("-"); want|=set(range(int(a),int(b)+1))
    else:
        want.add(int(part))
hz=100.0
tot=0.0
for line in open("/proc/stat"):
    f=line.split()
    if not f or not f[0].startswith("cpu") or f[0]=="cpu": continue
    try: n=int(f[0][3:])
    except ValueError: continue
    if n not in want: continue
    v=[int(x) for x in f[1:11]]
    idle=v[3]+v[4]           # idle + iowait
    tot += (sum(v)-idle)/hz
print(tot)' "$1"
}

# Best-effort page-cache warm pre-pass. This is a CPU measurement; a cold read
# would attribute page-fault/IO stalls to the engine.
ws0_warm_prepass() {
  local client_cpus="$1" secs="${2:-45}" logfile="$3"
  ws0_log "warm pre-pass ${secs}s (page cache)"
  taskset -c "$client_cpus" "$WS0_LOADGEN_BIN" \
      --endpoint "$WS0_ENDPOINT" --ticket-template "$WS0_TICKET_TPL" \
      --shape full --ramp 1 --step-duration "${secs}s" --seed "$WS0_SEED" \
      --round prewarm --out /dev/null >"$logfile" 2>&1 || \
    ws0_warn "warm pre-pass returned non-zero (see $logfile) — continuing"
}
