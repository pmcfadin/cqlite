  [ -x "$WS0_FLIGHT_BIN" ]  || ws0_die "WS0_FLIGHT_BIN=$WS0_FLIGHT_BIN is not executable"
  [ -n "$WS0_LOADGEN_BIN" ] || ws0_die "WS0_LOADGEN_BIN unset (path to flight-loadgen)"
