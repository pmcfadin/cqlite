//! Issue #1190 (epic #969): whole-artifact byte parity of CQLite writer output
//! against committed Cassandra 5.0.2-written reference SSTables.
//!
//! This is the FIRST test that diffs a *finished* CQLite-written SSTable
//! file-vs-file against a Cassandra-written reference for the same logical
//! schema/data (not a derived-value invariant, not a round-trip). It backs the
//! upgrade of two `write_load_path` parity-manifest scenarios from `partial` to
//! `byte_for_byte`:
//!
//!   * cass.write_load_path.cql_sstable_writer.finished_data_db_artifacts
//!     → `finished_data` (int PK, one text col): a finished Data.db artifact.
//!   * cass.write_load_path.flush.partition_boundary_artifacts
//!     → `partition_boundary` (int PK, int CK, text col; two partitions, several
//!     clustering rows each): partition-boundary Data.db + Index.db layout.
//!
//! The reference fixtures are generated by
//! `test-data/scripts/generate-write-load-parity.sh` (Cassandra 5.0.2, sha
//! f278f6774fc76465c182041e081982105c3e7dbb) and committed under
//! `test-data/datasets/sstables/test_writeparity/`. CQLite re-emits the exact
//! same logical input (same fixed writetime `T_WRITE`, same int keys, same text
//! values) via `SSTableWriter` and the bytes are compared.
//!
//! DETERMINISM CONTRACT (why two independent writers can byte-match):
//!   * Every cell uses the single fixed writetime `T_WRITE`, so the
//!     EncodingStats.minTimestamp delta baseline is identical (verified by the
//!     committed `*-Statistics.db.txt`: `EncodingStats minTimestamp: 1700000000000000`).
//!   * Tables are UNCOMPRESSED, so Data.db is a direct byte slice (no chunk
//!     framing differences).
//!   * Partition keys are int / (int,int): identical 4-byte big-endian key
//!     bytes and identical token ordering on both writers.
//!   * No TTL and no DELETE in these two tables. TTL/DELETE `localDeletionTime`
//!     is wall-clock-derived (`nowInSeconds`) and CANNOT byte-match across two
//!     independent writers — that is why the tombstone/TTL scenario stays
//!     `partial` (its byte SHAPE is anchored by issue_764 / issue_821 against
//!     derived expected values, not a whole-artifact diff).
//!
//! WHICH COMPONENTS ARE BYTE-FOR-BYTE (verified empirically against the
//! committed reference):
//!   * Data.db, Index.db, Summary.db, Digest.crc32 → BYTE-IDENTICAL. These are
//!     the data artifact, the partition/row offset table, the summary index, and
//!     the whole-file CRC32. They are diffed byte-for-byte here; any mismatch
//!     FAILS. This is the byte parity backing the scenario upgrades.
//!   * Filter.db and Statistics.db → NOT byte-comparable across two independent
//!     writers: Filter.db embeds implementation-specific bloom-filter sizing
//!     (bucket count / hash count), and Statistics.db embeds metadata histograms,
//!     cardinality (HyperLogLog), and host/encoding bookkeeping. CQLite emits
//!     both, but their bytes are an implementation detail, not a parity target.
//!     Their semantic content is covered elsewhere (Filter membership, Statistics
//!     min/max/EncodingStats are anchored by issue_764 / issue_821).
//!   * CRC.db → KNOWN WRITER GAP: Cassandra emits an (uncompressed-chunk) CRC.db
//!     component even for uncompressed BIG SSTables; CQLite's writer does not yet
//!     emit it (the READ side recognizes it — see
//!     cass.sstable_format.toc_component_manifest). This is a real
//!     component-completeness gap recorded as a pinned reference-only assertion
//!     below (the reference HAS CRC.db, CQLite does NOT). It is tracked as a
//!     separate writer issue; it does not affect any emitted file's bytes.
//!
//! Dataset-dependency doctrine (issue #719 / parity mandate):
//!   * If `CQLITE_DATASETS_ROOT` is unset OR the reference Data.db is genuinely
//!     absent (binaries not fetched), the test SKIPS (returns early with a note).
//!   * If the reference is PRESENT but empty / 0-rows, that is a FAILURE — a
//!     present-but-empty fixture must never silently pass.

#![cfg(feature = "write-support")]

use cqlite_core::schema::{Column, ClusteringColumn, ClusteringOrder, KeyColumn, TableSchema};
use cqlite_core::storage::sstable::writer::{SSTableFormat, SSTableWriter};
use cqlite_core::storage::write_engine::mutation::{
    CellOperation, ClusteringKey, DecoratedKey, Mutation, PartitionKey, TableId,
};
use cqlite_core::types::Value;
use std::collections::{BTreeSet, HashMap};
use std::path::{Path, PathBuf};
use tempfile::TempDir;

/// The single fixed writetime (micros). MUST match the `T_WRITE` constant in
/// `test-data/scripts/generate-write-load-parity.sh`.
const T_WRITE: i64 = 1_700_000_000_000_000;

const KEYSPACE: &str = "test_writeparity";

// ---------------------------------------------------------------------------
// Fixture resolution (skip-on-absence; present-but-empty is a failure)
// ---------------------------------------------------------------------------

/// Resolve the committed Cassandra reference directory for `table` under
/// `test_writeparity`. Returns `None` when the dataset root is unset or the
/// table's reference SSTable has not been fetched (genuine absence → skip).
fn reference_dir(table: &str) -> Option<PathBuf> {
    let root = std::env::var("CQLITE_DATASETS_ROOT").ok()?;
    let base = Path::new(&root).join("sstables").join(KEYSPACE);
    let entries = std::fs::read_dir(&base).ok()?;
    for e in entries.flatten() {
        let name = e.file_name().to_string_lossy().to_string();
        if name.starts_with(&format!("{table}-")) {
            let dir = e.path();
            // Genuine absence = no Data.db committed/fetched yet.
            if dir.join("nb-1-big-Data.db").is_file() {
                return Some(dir);
            }
            return None;
        }
    }
    None
}

/// Read a reference component file. Panics if a *present* reference directory is
/// missing a component (a fetched-but-broken fixture is a real failure, never a
/// silent skip).
fn read_component(dir: &Path, suffix: &str) -> Vec<u8> {
    let path = dir.join(format!("nb-1-big-{suffix}"));
    std::fs::read(&path).unwrap_or_else(|e| {
        panic!("reference component {path:?} unreadable in a present fixture: {e}")
    })
}

// ---------------------------------------------------------------------------
// CQLite writer harness
// ---------------------------------------------------------------------------

/// Write `mutations` for `schema` through the real `SSTableWriter` (BIG/nb,
/// uncompressed) and return the finished component directory.
async fn cqlite_write(schema: &TableSchema, mutations: Vec<Mutation>) -> (TempDir, PathBuf) {
    let dir = TempDir::new().expect("tempdir");
    let mut writer =
        SSTableWriter::with_format(dir.path().to_path_buf(), 1, schema, 16, SSTableFormat::Big)
            .expect("writer");

    // Decorate and group by partition key in ascending token order (the writer
    // requires strict token ordering and one write_partition call per key).
    let mut keyed: Vec<(DecoratedKey, Mutation)> = mutations
        .into_iter()
        .map(|m| (m.decorated_key(schema).expect("decorated key"), m))
        .collect();
    keyed.sort_by_key(|(k, _)| k.token);

    let mut grouped: Vec<(DecoratedKey, Vec<Mutation>)> = Vec::new();
    for (k, m) in keyed {
        match grouped.last_mut() {
            Some((lk, ms)) if lk.token == k.token && lk.key == k.key => ms.push(m),
            _ => grouped.push((k, vec![m])),
        }
    }
    for (k, ms) in grouped {
        writer.write_partition(k, ms).expect("write_partition");
    }
    let info = writer.finish().await.expect("finish");
    let table_dir = info
        .data_path
        .parent()
        .expect("data parent")
        .to_path_buf();
    (dir, table_dir)
}

/// Set of component suffixes present in a directory (strips the `nb-1-big-`
/// descriptor prefix so CQLite (`nb-1-big-`) and Cassandra (`nb-1-big-`) compare
/// on the logical component name).
fn component_suffixes(dir: &Path) -> BTreeSet<String> {
    let mut set = BTreeSet::new();
    if let Ok(rd) = std::fs::read_dir(dir) {
        for e in rd.flatten() {
            let name = e.file_name().to_string_lossy().to_string();
            if let Some(idx) = name.find("-big-") {
                set.insert(name[idx + 5..].to_string());
            } else if name.contains("TOC") {
                set.insert("TOC.txt".to_string());
            }
        }
    }
    // Drop derived/golden sidecars that only exist in the committed reference
    // tree (not emitted by either writer): JSONL + sstablemetadata text.
    set.retain(|s| !s.ends_with(".jsonl") && !s.ends_with("Statistics.db.txt"));
    set
}

/// TOC.txt content as a set of trimmed non-empty component lines.
fn toc_set(toc_bytes: &[u8]) -> BTreeSet<String> {
    String::from_utf8_lossy(toc_bytes)
        .lines()
        .map(|l| l.trim().to_string())
        .filter(|l| !l.is_empty())
        .collect()
}

/// First differing byte index, if any.
fn first_diff(a: &[u8], b: &[u8]) -> Option<usize> {
    let n = a.len().max(b.len());
    (0..n).find(|&i| a.get(i) != b.get(i))
}

