fn finished_mutations() -> Vec<Mutation> {
    (0..6)
        .map(|i| {
            Mutation::new(
                TableId::new(KEYSPACE, "finished_data"),
                PartitionKey::single("id", Value::Integer(i)),
                None,
                vec![CellOperation::Write {
                    column: "name".into(),
                    value: Value::Text(format!("name{i}")),
                }],
                T_WRITE,
                None,
            )
        })
        .collect()
}

fn partition_boundary_mutations() -> Vec<Mutation> {
    let mut muts = Vec::new();
    for ck in 1..=4 {
        muts.push(Mutation::new(
            TableId::new(KEYSPACE, "partition_boundary"),
            PartitionKey::single("id", Value::Integer(1)),
            Some(ClusteringKey::single("ck", Value::Integer(ck))),
            vec![CellOperation::Write {
                column: "v".into(),
                value: Value::Text(format!("v_1_{ck}")),
            }],
            T_WRITE,
            None,
        ));
    }
    for ck in 1..=2 {
        muts.push(Mutation::new(
            TableId::new(KEYSPACE, "partition_boundary"),
            PartitionKey::single("id", Value::Integer(2)),
            Some(ClusteringKey::single("ck", Value::Integer(ck))),
            vec![CellOperation::Write {
                column: "v".into(),
                value: Value::Text(format!("v_2_{ck}")),
            }],
            T_WRITE,
            None,
        ));
    }
    muts
}

// ---------------------------------------------------------------------------
// Shared whole-artifact byte-parity assertion
// ---------------------------------------------------------------------------

/// Diff a CQLite-written SSTable against the Cassandra reference for `table`:
/// component presence, TOC.txt, full Data.db bytes, full Index.db bytes (the
/// partition/row offset table), AND the committed sstabledump JSONL golden
/// (non-empty / expected partition count). Any mismatch FAILS.
///
/// `expected_jsonl_partitions` is the number of partitions the committed JSONL
/// golden must contain (present-but-empty / wrong-count is a failure).
async fn assert_byte_parity(
    table: &str,
    schema: TableSchema,
    mutations: Vec<Mutation>,
    expected_jsonl_partitions: usize,
) {
    let Some(ref_dir) = reference_dir(table) else {
        eprintln!(
            "[issue_1190] reference for {KEYSPACE}.{table} absent (dataset not fetched); skipping"
        );
        return;
    };

    let (_guard, out_dir) = cqlite_write(&schema, mutations).await;

    // 1. Component presence: every component CQLite emits must be present in the
    //    reference (no spurious CQLite-only component), and the byte-parity data
    //    components must be present on BOTH sides.
    let ref_components = component_suffixes(&ref_dir);
    let our_components = component_suffixes(&out_dir);
    assert!(
        !ref_components.is_empty(),
        "{table}: reference component set is empty (broken fixture)"
    );
    for needed in ["Data.db", "Index.db", "Summary.db", "Digest.crc32", "Statistics.db", "Filter.db", "TOC.txt"] {
        assert!(
            ref_components.contains(needed),
            "{table}: reference missing required component {needed}; have {ref_components:?}"
        );
        assert!(
            our_components.contains(needed),
            "{table}: CQLite output missing component {needed}; have {our_components:?}"
        );
    }
    // Pinned KNOWN GAP: Cassandra emits CRC.db for uncompressed BIG SSTables;
    // CQLite's writer does not yet. If this ever flips (CQLite starts emitting
    // CRC.db), this assertion fails and forces a manifest review — we must never
    // silently claim component-set parity while a component is missing.
    assert!(
        ref_components.contains("CRC.db"),
        "{table}: reference unexpectedly lacks CRC.db (regenerate fixtures?)"
    );
    assert!(
        !our_components.contains("CRC.db"),
        "{table}: CQLite now emits CRC.db — the known writer gap is closed; \
         re-evaluate write_load_path component-set parity in the manifest"
    );

    // 2. TOC.txt: every component CQLite lists must match the reference TOC; the
    //    only allowed difference is the known-missing CRC.db line.
    let ref_toc = toc_set(&read_component(&ref_dir, "TOC.txt"));
    let our_toc = toc_set(&std::fs::read(out_dir.join("nb-1-big-TOC.txt")).expect("our TOC"));
    let ref_toc_no_crc: BTreeSet<String> =
        ref_toc.iter().filter(|c| *c != "CRC.db").cloned().collect();
    assert_eq!(
        ref_toc_no_crc, our_toc,
        "{table}: TOC.txt component set differs beyond the known CRC.db gap \
         (cass-minus-CRC={ref_toc_no_crc:?} ours={our_toc:?})"
    );

    // 3. Data.db: full byte equality (row layout, headers, offsets, cells).
    assert_component_bytes(table, &ref_dir, &out_dir, "Data.db");

    // 4. Index.db: full byte equality (partition key + Data.db offset table =
    //    the partition/row-offset layout). This is the partition-boundary check.
    assert_component_bytes(table, &ref_dir, &out_dir, "Index.db");

    // 5. Summary.db + Digest.crc32: full byte equality (summary offset index and
    //    whole-file CRC32). Completes the deterministic byte-parity component set.
    assert_component_bytes(table, &ref_dir, &out_dir, "Summary.db");
    assert_component_bytes(table, &ref_dir, &out_dir, "Digest.crc32");

    // 6. sstabledump JSONL golden: must exist, be non-empty, and contain exactly
    //    the expected partition count. Present-but-empty / 0-rows is a failure.
    let jsonl = ref_dir.join("nb-1-big-Data.db.jsonl");
    let jsonl_text = std::fs::read_to_string(&jsonl)
        .unwrap_or_else(|e| panic!("{table}: committed JSONL golden {jsonl:?} unreadable: {e}"));
    let partitions: Vec<&str> = jsonl_text
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .collect();
    assert!(
        !partitions.is_empty(),
        "{table}: committed JSONL golden is present-but-empty (0 partitions) — parity failure"
    );
    assert_eq!(
        partitions.len(),
        expected_jsonl_partitions,
        "{table}: JSONL golden partition count {} != expected {expected_jsonl_partitions}",
        partitions.len()
    );
    for (i, line) in partitions.iter().enumerate() {
        let v: serde_json::Value = serde_json::from_str(line)
            .unwrap_or_else(|e| panic!("{table}: JSONL partition {i} is not valid JSON: {e}"));
        let rows = v.get("rows").and_then(|r| r.as_array());
        assert!(
            rows.is_some_and(|r| !r.is_empty()),
            "{table}: JSONL partition {i} has no rows — parity failure"
        );
    }
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

/// Assert a CQLite-written component byte-matches the Cassandra reference.
/// Present-but-empty reference is a failure; any byte mismatch FAILS with a
/// first-diff report.
fn assert_component_bytes(table: &str, ref_dir: &Path, out_dir: &Path, suffix: &str) {
    let reference = read_component(ref_dir, suffix);
    let ours = std::fs::read(out_dir.join(format!("nb-1-big-{suffix}")))
        .unwrap_or_else(|e| panic!("{table}: CQLite {suffix} unreadable: {e}"));
    assert!(
        !reference.is_empty(),
        "{table}: reference {suffix} is present-but-empty — parity failure"
    );
    if reference != ours {
        let at = first_diff(&reference, &ours);
        panic!(
            "{table}: {suffix} byte mismatch (cass={} ours={} bytes, first diff at {:?})\n  cass={}\n  ours={}",
            reference.len(),
            ours.len(),
            at,
            hex(&reference),
            hex(&ours),
        );
    }
}

// ---------------------------------------------------------------------------
// Scenario 1: finished_data_db_artifacts — finished Data.db artifact.
// ---------------------------------------------------------------------------

/// Whole-artifact byte parity: CQLite's finished `finished_data` SSTable
/// (Data.db / Index.db / TOC.txt / components) is byte-identical to the
/// Cassandra 5.0.2 reference, and the committed JSONL golden has the 6 written
/// partitions. Backs
/// `cass.write_load_path.cql_sstable_writer.finished_data_db_artifacts`.
#[tokio::test]
async fn finished_data_db_artifacts_byte_for_byte() {
    assert_byte_parity("finished_data", finished_schema(), finished_mutations(), 6).await;
}

// ---------------------------------------------------------------------------
// Scenario 2: partition_boundary_artifacts — partition/row offset layout.
// ---------------------------------------------------------------------------

/// Whole-artifact byte parity: CQLite's finished `partition_boundary` SSTable
/// (multi-partition, multi-clustering-row) is byte-identical to the Cassandra
/// 5.0.2 reference, including the Index.db partition/row-offset table, and the
/// committed JSONL golden has the 2 written partitions. Backs
/// `cass.write_load_path.flush.partition_boundary_artifacts`.
#[tokio::test]
async fn partition_boundary_artifacts_byte_for_byte() {
    assert_byte_parity(
        "partition_boundary",
        partition_boundary_schema(),
        partition_boundary_mutations(),
        2,
    )
    .await;
}
