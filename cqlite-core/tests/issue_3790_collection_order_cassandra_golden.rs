//! Issue #3790, acceptance criterion 3 — the `inet` / `time` collection-ordering
//! oracle read out of **Cassandra-written bytes**, not out of a CQLite round-trip.
//!
//! # Why this file exists
//!
//! `cqlite-core/tests/issue_3790_inet_time_value_ordering.rs` pins the comparator
//! against hand-constructed `Value`s. That is necessary and it is not sufficient:
//! it asserts what CQLite's comparator does, and nothing about what Cassandra
//! actually wrote. A CQLite-written + CQLite-read round-trip would be no better —
//! it is **invariant to a uniform ordering error**, because the writer and the
//! reader make the identical mistake, the round-trip closes, and the test stays
//! green while real Cassandra data reads misordered (CLAUDE.md, #3042).
//!
//! So the oracle here is a real Cassandra 5.0.2 SSTable:
//! `test-data/datasets/sstables/test_comparator_order/collection_order-*/`
//! (`nb` BIG, uncompressed, no TTL), generated by
//! `test-data/scripts/generate-issue-3790-comparator-ordering.sh` from
//! `test-data/schemas/issue-3790-comparator-ordering.cql`. The README beside the
//! fixture is the written oracle; the `sstabledump` golden `nb-1-big-Data.db.jsonl`
//! is the machine-readable form of it, and this test reads the golden rather than
//! trusting the prose.
//!
//! # Format authority
//!
//! Never a CQLite `file:line` (#3041). At the pinned tag `cassandra-5.0.8`:
//!
//! * `src/java/org/apache/cassandra/db/marshal/InetAddressType.java` —
//!   `InetAddressType() { super(ComparisonType.BYTE_ORDER); }`
//! * `src/java/org/apache/cassandra/db/marshal/TimeType.java` —
//!   `private TimeType() { super(ComparisonType.BYTE_ORDER); }`
//!
//! `ComparisonType.BYTE_ORDER` is `ByteBufferUtil.compareUnsigned`. For a
//! NON-FROZEN collection the element (SET) or key (MAP) *is* the cell path, so
//! that comparator decides the on-disk cell order — which is what makes the
//! property observable in Cassandra-written bytes at all.
//!
//! # What each leg proves
//!
//! **Leg 1 — the golden vs the comparator.** Take each complex column's cell-path
//! sequence *in file order* (the order Cassandra wrote it), transcribe each path
//! into the `Value` it denotes, and require `ComparatorType` to reproduce exactly
//! that sequence: every adjacent-and-non-adjacent pair `Less` in file order, and a
//! sort of a scrambled permutation landing back on it. The file order is
//! additionally cross-checked against the README's hardcoded oracle, so a
//! regenerated or corrupted golden cannot silently false-pass. Negative controls
//! assert the *wrong* implementations produce a DIFFERENT order, so the assertions
//! provably have teeth rather than being satisfiable by any total order.
//!
//! **Leg 2 — CQLite reads the same order off the same bytes.** Decode the real
//! `nb-1-big-Data.db` through the ungated `SSTableReader` compaction iterator,
//! which surfaces each complex column's per-element cells in on-disk order with
//! their decoded values, and assert (a) the decoded values equal Leg 1's
//! transcription — i.e. Leg 1 reasoned about the values the bytes really carry —
//! and (b) sorting those DECODED values with `ComparatorType` reproduces the
//! on-disk order. Leg 2 alone would be weak (a dump path that never re-orders
//! prints the right sequence with or without the fix, as the fixture README warns);
//! its value is that it closes the loop Cassandra bytes -> CQLite decode ->
//! CQLite comparator -> Cassandra's order.
//!
//! # HONEST SCOPE — `time` is a LATENT case, and this file does not overclaim it
//!
//! CQLite renders `time` as `TIME(HH:MM:SS.nnnnnnnnn)` (`types.rs::fmt_time`),
//! fixed-width and zero-padded, so over the whole valid range
//! `0..=86_399_999_999_999` the formatted-string order and the nanosecond order
//! **coincide**. No `time` value — in this fixture or any other — can falsify the
//! formatted-string implementation. The `time` assertions below are therefore a
//! **value-order pin against future regression**, plus a falsifier for a
//! *decimal-nanosecond string* comparison (`9000000000 < 10000000000` numerically
//! while `"9000000000" > "10000000000"` lexicographically). `inet` is the column
//! that catches the live defect. Any reading of this file as demonstrating a
//! caught `time` misordering is wrong.
//!
//! # RED-verified (measured, not asserted)
//!
//! With the `inet`/`time` arms of `types::comparator::custom::compare` removed —
//! i.e. both types back on the formatted-string fallback that was the #3790
//! defect — **7 of these 11 cases FAIL**: every `inet` case and every composite
//! case, in BOTH legs, plus the formatted-string negative control. The four that
//! still pass are exactly the `time` ones and the whole-tuple-path control,
//! which is the LATENT-`time` scope above measured rather than merely claimed. A
//! green ordering test that has never been shown to red proves nothing.
//!
//! # Gate
//!
//! **Deliberately UNGATED at file level.** A crate-level `#![cfg(feature = ...)]`
//! on a `delta-scan` / `observability-testing` feature would put this target in the
//! set that COMPILES in every lane and EXECUTES in none (CLAUDE.md, #3522) — which
//! is exactly what happened to the otherwise-excellent
//! `issue_1295_signed_collection_order_parity.rs`. The gate of record's
//! `core-tests` runs `cargo test -p cqlite-core --features cli-helpers`, so an
//! ungated target executes there; nothing here needs a non-default feature.
//!
//! The fixture is **git-committed**, so it is `must_run` (#3220): failure to
//! resolve it is a hard FAILURE, never a skip, and a present fixture decoding to
//! zero rows/elements is a hard failure too.
//!
//! ```bash
//! cargo test -p cqlite-core --features cli-helpers \
//!   --test issue_3790_collection_order_cassandra_golden -- --nocapture
//! ```

