// LEG 1 negative controls — the assertions above have teeth.
//
// A green ordering test proves nothing unless the WRONG implementations are
// shown to produce a DIFFERENT answer. These cases construct the wrong orders
// explicitly and assert they diverge from the Cassandra-written one.
// ===========================================================================

/// Formatted-string order (the #3790 defect) does NOT reproduce the golden.
///
/// Three independent falsifying pairs, inverting in both the v4/v4 and the v4/v6
/// direction, so no single coincidence satisfies them all.
#[test]
fn negative_control_formatted_string_order_diverges_from_cassandra_for_inet() {
    let golden = load_golden(&fixture_dir().join(GOLDEN_FILE));
    let on_disk = golden_order(&golden, "1", "inet_set");

    let mut by_string: Vec<Value> = on_disk.iter().map(|p| inet_value(p)).collect();
    by_string.sort_by_key(|v| format!("{v}"));
    let expected: Vec<Value> = on_disk.iter().map(|p| inet_value(p)).collect();
    assert_ne!(
        by_string, expected,
        "if formatted-string order reproduced the Cassandra order, this fixture \
         could not catch the #3790 defect at all"
    );

    for (lo, hi) in [
        ("9.0.0.1", "10.0.0.2"),
        ("2001:db8:0:0:0:0:0:1", "192.168.0.1"),
        ("9.0.0.1", "2001:db8:0:0:0:0:0:1"),
    ] {
        let (lo_v, hi_v) = (inet_value(lo), inet_value(hi));
        assert_eq!(
            inet_comparator().compare(&lo_v, &hi_v).expect("compare"),
            Ordering::Less,
            "byte order: {lo} < {hi}"
        );
        assert!(
            format!("{lo_v}") > format!("{hi_v}"),
            "the pair must INVERT under formatted-string comparison, else it is \
             not a falsifier: {lo} vs {hi}"
        );
    }
}

/// `time`: the honest negative control.
///
/// There is deliberately NO formatted-string falsifier here — `fmt_time` is
/// fixed-width and zero-padded, so string order and nanosecond order coincide
/// over the whole valid range, and this case ASSERTS that coincidence rather
/// than pretending otherwise. What the fixture does falsify is a
/// DECIMAL-NANOSECOND string comparison, the other plausible wrong
/// implementation.
#[test]
fn negative_control_time_falsifies_decimal_nanos_strings_but_not_fmt_time() {
    let golden = load_golden(&fixture_dir().join(GOLDEN_FILE));
    let on_disk = golden_order(&golden, "1", "time_set");
    let expected: Vec<Value> = on_disk.iter().map(|p| time_value(p)).collect();

    // (a) fmt_time order COINCIDES with the on-disk order — the latency, stated.
    let mut by_fmt: Vec<Value> = expected.clone();
    by_fmt.sort_by_key(|v| format!("{v}"));
    assert_eq!(
        by_fmt, expected,
        "fmt_time is fixed-width and zero-padded, so string order and nanosecond \
         order coincide; a `time` value that falsified fmt_time would mean the \
         renderer changed, not that this test got stronger"
    );

    // (b) a DECIMAL-NANOSECOND string comparison IS falsified: 00:00:09 and
    //     00:00:10 are 9000000000 and 10000000000 nanos.
    let nine = time_nanos("00:00:09.000000000");
    let ten = time_nanos("00:00:10.000000000");
    assert_eq!(nine, 9_000_000_000);
    assert_eq!(ten, 10_000_000_000);
    assert!(
        nine.to_string() > ten.to_string(),
        "\"9…\" > \"10…\" as text"
    );
    assert_eq!(
        time_comparator()
            .compare(&Value::Time(nine), &Value::Time(ten))
            .expect("time compare"),
        Ordering::Less,
        "nanosecond (byte) order, not decimal-string order"
    );
}

