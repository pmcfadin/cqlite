/// `inet` as a SET element and as a MAP key, both partitions.
///
/// This is the case that catches the LIVE defect: `9.0.0.1` before `10.0.0.2`
/// by bytes, the reverse by formatted string.
#[test]
fn leg1_golden_inet_order_is_reproduced_by_the_comparator() {
    let golden = load_golden(&fixture_dir().join(GOLDEN_FILE));
    let cmp = inet_comparator();
    for column in ["inet_set", "inet_map"] {
        assert_column(&golden, "1", column, ORACLE_INET_ROW1, &cmp, inet_value);
        assert_column(&golden, "2", column, ORACLE_INET_ROW2, &cmp, inet_value);
    }
}

/// The single pair the #3790 defect got wrong, asserted on its own so a failure
/// names it rather than hiding inside a six-element sequence.
#[test]
fn leg1_cassandra_puts_9_0_0_1_before_10_0_0_2() {
    let golden = load_golden(&fixture_dir().join(GOLDEN_FILE));
    for column in ["inet_set", "inet_map"] {
        for partition in ["1", "2"] {
            let order = golden_order(&golden, partition, column);
            let nine = order
                .iter()
                .position(|p| p == "9.0.0.1")
                .unwrap_or_else(|| panic!("{column}/{partition}: 9.0.0.1 absent from the golden"));
            let ten = order
                .iter()
                .position(|p| p == "10.0.0.2")
                .unwrap_or_else(|| panic!("{column}/{partition}: 10.0.0.2 absent from the golden"));
            assert!(
                nine < ten,
                "{column}/partition {partition}: Cassandra wrote 9.0.0.1 (0x09…) \
                 BEFORE 10.0.0.2 (0x0a…); the golden says otherwise"
            );
        }
    }
    let cmp = inet_comparator();
    assert_eq!(
        cmp.compare(&inet_value("9.0.0.1"), &inet_value("10.0.0.2"))
            .expect("inet compare"),
        Ordering::Less,
        "the comparator must agree with the Cassandra-written order, not with \
         formatted-string order (\"10.0.0.2\" < \"9.0.0.1\" as text)"
    );
}

