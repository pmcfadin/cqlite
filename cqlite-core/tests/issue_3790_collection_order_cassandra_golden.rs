/// `pair_set` is INET-MAJOR, TIME-MINOR, and both halves are load-bearing.
///
/// Partition 2 separates inet-major from time-major: on disk `9.0.0.1` at
/// `00:00:10` precedes `10.0.0.2` at `00:00:09`, so the time components run
/// BACKWARDS relative to the element order. Partition 1's entries 2 and 3 share
/// `10.0.0.2` and differ only in the time component, so the minor key decides
/// there.
#[test]
fn leg1_composite_is_inet_major_and_the_time_component_is_load_bearing() {
    let golden = load_golden(&fixture_dir().join(GOLDEN_FILE));
    let cmp = pair_comparator();

    // Inet-major: the first component decides AGAINST the time components' order.
    let row2 = golden_order(&golden, "2", "pair_set");
    assert_eq!(row2, ORACLE_PAIR_ROW2);
    let (first_addr, first_time) = split_tuple_path(&row2[0]);
    let (second_addr, second_time) = split_tuple_path(&row2[1]);
    assert_eq!(
        (first_addr.as_str(), second_addr.as_str()),
        ("9.0.0.1", "10.0.0.2")
    );
    assert!(
        time_nanos(&first_time) > time_nanos(&second_time),
        "partition 2's element order must run OPPOSITE to its time components, or \
         it cannot distinguish inet-major from time-major"
    );
    assert_eq!(
        cmp.compare(&pair_value(&row2[0]), &pair_value(&row2[1]))
            .expect("tuple compare"),
        Ordering::Less
    );

    // Time-minor: two entries sharing an inet are separated by the time alone.
    let row1 = golden_order(&golden, "1", "pair_set");
    let (a_addr, a_time) = split_tuple_path(&row1[1]);
    let (b_addr, b_time) = split_tuple_path(&row1[2]);
    assert_eq!(
        (a_addr.as_str(), b_addr.as_str()),
        ("10.0.0.2", "10.0.0.2"),
        "entries 2 and 3 must share an address for the minor key to be exercised"
    );
    assert!(time_nanos(&a_time) < time_nanos(&b_time));
    assert_eq!(
        cmp.compare(&pair_value(&row1[1]), &pair_value(&row1[2]))
            .expect("tuple compare"),
        Ordering::Less,
        "with the inet components equal, the time component must decide"
    );
}

