// ===========================================================================
// Fixture resolution — committed, therefore must_run (#3220): fail closed.
// ===========================================================================

fn fixture_dir() -> PathBuf {
    let root = sstables_root_for_table(KEYSPACE, TABLE).unwrap_or_else(|| {
        panic!(
            "{KEYSPACE}.{TABLE} is COMMITTED to git and must resolve in every \
             checkout, unconditionally (#3220) — {}",
            describe_search(KEYSPACE, TABLE)
        )
    });
    let ks = root.join(KEYSPACE);

    // AMBIGUITY IS A HARD FAILURE, NOT A CHOICE (roborev job 42, findings 1+3).
    //
    // This used to take the FIRST prefix-matching directory and `break`, which is
    // wrong in two reachable ways, and both of them pass silently:
    //
    //   1. STALE GENERATION. Regenerating the fixture produces a NEW `<uuid>`
    //      directory. If the previous one is still committed (the generator's
    //      printed staging commands used to add the new files without staging the
    //      old directory's DELETION), the keyspace holds two generations and the
    //      winner is whatever `read_dir` yields first — i.e. this test would
    //      validate the CORRECT comparator against a STALE oracle, or vice versa.
    //   2. SHADOWING. `sstables_root_for_table` searches `$CQLITE_DATASETS_ROOT`
    //      BEFORE the checkout, so an out-of-tree corpus that happens to carry a
    //      `test_comparator_order/collection_order-*` would silently replace the
    //      COMMITTED oracle this test exists to assert against.
    //
    // `read_dir` order is filesystem-dependent, so either case is a test that
    // passes or fails for reasons unrelated to the code under review. We therefore
    // require EXACTLY ONE candidate carrying BOTH halves of the committed oracle
    // (the Cassandra-written `*-Data.db` and its `*-Data.db.jsonl` golden), and
    // panic naming every candidate otherwise. Fail-closed: a fixture we cannot
    // identify unambiguously is not an oracle.
    let mut candidates: Vec<PathBuf> = std::fs::read_dir(&ks)
        .unwrap_or_else(|e| panic!("read keyspace dir {ks:?}: {e}"))
        .flatten()
        .map(|e| e.path())
        .filter(|p| {
            p.is_dir()
                && p.file_name()
                    .and_then(|n| n.to_str())
                    .is_some_and(|n| n.starts_with(&format!("{TABLE}-")))
        })
        .filter(|p| {
            let has = |suffix: &str| {
                std::fs::read_dir(p).is_ok_and(|rd| {
                    rd.flatten().any(|e| {
                        e.file_name()
                            .to_str()
                            .is_some_and(|n| n.ends_with(suffix))
                    })
                })
            };
            has("-Data.db") && has("-Data.db.jsonl")
        })
        .collect();
    candidates.sort();

    match candidates.len() {
        1 => candidates.remove(0),
        0 => panic!(
            "no {TABLE}-<uuid> directory under {ks:?} carries BOTH a *-Data.db and its \
             *-Data.db.jsonl golden. {KEYSPACE}.{TABLE} is COMMITTED to git and must \
             resolve in every checkout, unconditionally (#3220: must_run) — {}",
            describe_search(KEYSPACE, TABLE)
        ),
        n => panic!(
            "AMBIGUOUS fixture: {n} {TABLE}-<uuid> directories under {ks:?} each carry a \
             *-Data.db + golden, so which one this test asserts against would depend on \
             filesystem order. Leave exactly ONE generation committed (a regeneration must \
             stage the previous directory's DELETION, not just add the new files). \
             Candidates: {candidates:?}"
        ),
    }
}

// ===========================================================================
// Golden JSONL -> per-(partition, column) cell-path sequence IN FILE ORDER.
// ===========================================================================

/// One partition of the golden: `(column, Some(cell path))` per cell, in file
/// order. `None` is the path-less complex-column deletion shell Cassandra writes
/// ahead of a whole-collection assignment.
type GoldenCells = Vec<(String, Option<String>)>;

/// Every partition of the golden: `(partition key as rendered by sstabledump,
/// cells)`.
type Golden = Vec<(String, GoldenCells)>;

/// Every partition of the golden, as `(partition key string, cells)` where a
/// cell is `(column, Option<path>)`. The path-less cell is the complex-column
/// deletion shell Cassandra writes ahead of a whole-collection assignment; it is
/// skipped by [`golden_order`] rather than dropped here, so a golden that lost
/// its cells entirely still shows up as an empty sequence and fails loudly.
fn load_golden(path: &std::path::Path) -> Golden {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| {
        panic!("golden {path:?} is committed alongside the fixture and must read: {e}")
    });
    let mut out = Vec::new();
    for line in text.lines().filter(|l| !l.trim().is_empty()) {
        let v: serde_json::Value =
            serde_json::from_str(line).unwrap_or_else(|e| panic!("parse golden line: {e}"));
        let key = v["partition"]["key"][0]
            .as_str()
            .unwrap_or_else(|| panic!("golden partition has no key"))
            .to_string();
        let mut cells = Vec::new();
        for row in v["rows"].as_array().into_iter().flatten() {
            for cell in row["cells"].as_array().into_iter().flatten() {
                let name = cell["name"]
                    .as_str()
                    .unwrap_or_else(|| panic!("golden cell has no name"))
                    .to_string();
                let path = cell["path"]
                    .as_array()
                    .and_then(|p| p.first())
                    .and_then(|p| p.as_str())
                    .map(str::to_string);
                cells.push((name, path));
            }
        }
        assert!(
            !cells.is_empty(),
            "golden partition {key} has no cells — a present-but-empty golden must \
             never pass"
        );
        out.push((key, cells));
    }
    assert_eq!(
        out.len(),
        2,
        "the fixture has exactly two partitions (id=1 the full case, id=2 the \
         minimal falsifying pair)"
    );
    out
}

/// The cell paths of one column of one partition, in FILE ORDER — i.e. the order
/// Cassandra's comparator put them in.
fn golden_order(golden: &Golden, partition: &str, column: &str) -> Vec<String> {
    let (_, cells) = golden
        .iter()
        .find(|(k, _)| k == partition)
        .unwrap_or_else(|| panic!("golden has no partition {partition}"));
    let order: Vec<String> = cells
        .iter()
        .filter(|(name, _)| name == column)
        .filter_map(|(_, path)| path.clone())
        .collect();
    assert!(
        !order.is_empty(),
        "column {column} of partition {partition} has no path-bearing cells in the \
         golden — a present fixture yielding zero elements is a hard failure"
    );
    order
}

// ===========================================================================
// Transcription: a sstabledump cell path -> the Value it denotes.
//
// Derived from Cassandra's rendering of the type, never from CQLite output:
// InetAddressType renders the address, TimeType renders HH:MM:SS.nnnnnnnnn, and
// a tuple path joins its components with `:` after escaping any `:` inside a
// component as `\:`.
// ===========================================================================

/// `9.0.0.1` / `2001:db8:0:0:0:0:0:1` -> the RAW serialized address bytes
/// (4 for IPv4, 16 for IPv6) — exactly what `InetAddressType` compares.
fn inet_value(rendered: &str) -> Value {
    let addr: IpAddr = rendered
        .parse()
        .unwrap_or_else(|e| panic!("golden inet path {rendered:?} is not an address: {e}"));
    match addr {
        IpAddr::V4(v4) => Value::inet(v4.octets().to_vec()),
        IpAddr::V6(v6) => Value::inet(v6.octets().to_vec()),
    }
}

/// `HH:MM:SS.nnnnnnnnn` -> nanoseconds since midnight, which is `TimeType`'s
/// serialized 8-byte big-endian long.
fn time_nanos(rendered: &str) -> i64 {
    let (hms, nanos) = rendered
        .split_once('.')
        .unwrap_or_else(|| panic!("golden time path {rendered:?} has no fractional part"));
    let parts: Vec<&str> = hms.split(':').collect();
    assert_eq!(
        parts.len(),
        3,
        "golden time path {rendered:?} is not HH:MM:SS.nnnnnnnnn"
    );
    let num = |s: &str| -> i64 {
        s.parse()
            .unwrap_or_else(|e| panic!("golden time path {rendered:?} component {s:?}: {e}"))
    };
    assert_eq!(
        nanos.len(),
        9,
        "golden time path {rendered:?} must carry 9 fractional digits"
    );
    ((num(parts[0]) * 60 + num(parts[1])) * 60 + num(parts[2])) * 1_000_000_000 + num(nanos)
}

fn time_value(rendered: &str) -> Value {
    Value::Time(time_nanos(rendered))
}

/// Split a sstabledump tuple path on its FIRST unescaped `:` and unescape each
/// component. `2001\:db8\:...\:1:00\:00\:10.000000000` therefore splits into the
/// IPv6 address and the time, not on the address's own colons.
fn split_tuple_path(path: &str) -> (String, String) {
    let mut component = String::new();
    let mut chars = path.chars();
    let mut consumed = 0usize;
    while let Some(c) = chars.next() {
        consumed += c.len_utf8();
        match c {
            '\\' => match chars.next() {
                Some(escaped) => {
                    consumed += escaped.len_utf8();
                    component.push(escaped);
                }
                None => panic!("tuple path {path:?} ends in a dangling escape"),
            },
            ':' => {
                let rest = &path[consumed..];
                return (component, rest.replace("\\:", ":"));
            }
            other => component.push(other),
        }
    }
    panic!("tuple path {path:?} has no unescaped component separator")
}

/// `(inet, time)` frozen tuple, as `pair_set`'s element type declares it.
fn pair_value(path: &str) -> Value {
    let (addr, at) = split_tuple_path(path);
    Value::Frozen(Box::new(Value::Tuple(vec![
        inet_value(&addr),
        time_value(&at),
    ])))
}

// ===========================================================================
// The comparators, built from the DECLARED CQL types (schema-driven, #28) —
// never hand-picked variants.
// ===========================================================================

fn inet_comparator() -> ComparatorType {
    ComparatorType::from_cql_type(&CqlType::Inet).expect("inet comparator")
}

fn time_comparator() -> ComparatorType {
    ComparatorType::from_cql_type(&CqlType::Time).expect("time comparator")
}

/// `pair_set` is `SET<FROZEN<TUPLE<INET, TIME>>>`; the SET's ELEMENT comparator
/// is what orders the cell paths.
fn pair_comparator() -> ComparatorType {
    ComparatorType::from_cql_type(&CqlType::Frozen(Box::new(CqlType::Tuple(vec![
        CqlType::Inet,
        CqlType::Time,
    ]))))
    .expect("frozen tuple comparator")
}

// ===========================================================================
// The core assertion.
// ===========================================================================

/// Require `cmp` to make `values` a strictly increasing sequence, and require a
/// scrambled permutation of it to sort back onto it.
///
/// Pairwise-over-ALL-pairs, not just adjacent ones: an "always Equal" or
/// otherwise degenerate comparator satisfies a sort trivially (a sort of an
/// already-ordered slice is a no-op for a stable sort), so the sort alone would
/// be a vacuous pass.
fn assert_strict_order(cmp: &ComparatorType, values: &[Value], what: &str) {
    assert!(
        values.len() >= 2,
        "{what}: an ordering claim needs at least two values, got {}",
        values.len()
    );
    for i in 0..values.len() {
        for j in (i + 1)..values.len() {
            let fwd = cmp
                .compare(&values[i], &values[j])
                .unwrap_or_else(|e| panic!("{what}: compare({i},{j}) failed: {e}"));
            assert_eq!(
                fwd,
                Ordering::Less,
                "{what}: Cassandra wrote element {i} before element {j}, so the \
                 comparator must order them Less — got {fwd:?} for {:?} vs {:?}",
                values[i],
                values[j]
            );
            let rev = cmp
                .compare(&values[j], &values[i])
                .unwrap_or_else(|e| panic!("{what}: compare({j},{i}) failed: {e}"));
            assert_eq!(
                rev,
                Ordering::Greater,
                "{what}: the comparator must be antisymmetric"
            );
        }
    }

    // Deterministic scrambles — every rotation of the REVERSED sequence — so the
    // sort is doing real work rather than confirming an already-sorted slice.
    // (A two-element sequence has exactly one such scramble; the identity
    // rotation is filtered out rather than asserted away.)
    let reversed: Vec<Value> = values.iter().rev().cloned().collect();
    let scrambles: Vec<Vec<Value>> = (0..reversed.len())
        .map(|shift| {
            let mut p = reversed.clone();
            p.rotate_left(shift);
            p
        })
        .filter(|p| p != values)
        .collect();
    assert!(
        !scrambles.is_empty(),
        "{what}: no scramble differs from the expected order — the sort below \
         would be a no-op and prove nothing"
    );
    for mut scrambled in scrambles {
        scrambled.sort_by(|a, b| {
            cmp.compare(a, b)
                .unwrap_or_else(|e| panic!("{what}: sort compare failed: {e}"))
        });
        assert_eq!(
            scrambled, values,
            "{what}: sorting with ComparatorType must reproduce the order \
             Cassandra wrote on disk"
        );
    }
}

/// One column of one partition: cross-check the golden's file order against the
/// README oracle, then require the comparator to reproduce it.
fn assert_column(
    golden: &Golden,
    partition: &str,
    column: &str,
    oracle: &[&str],
    cmp: &ComparatorType,
    transcribe: fn(&str) -> Value,
) -> Vec<Value> {
    let observed = golden_order(golden, partition, column);
    assert_eq!(
        observed, oracle,
        "{column} (partition {partition}): the golden's on-disk cell-path order \
         no longer matches the README oracle. Either the golden was regenerated \
         or it is corrupt — resolve THAT before touching the comparator."
    );
    let values: Vec<Value> = observed.iter().map(|p| transcribe(p)).collect();
    assert_strict_order(cmp, &values, &format!("{column}/partition {partition}"));
    values
}

